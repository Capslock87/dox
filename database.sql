-- Создание базы данных (если не существует)
CREATE DATABASE IF NOT EXISTS `green_crops_db`
    CHARACTER SET utf8mb4
    COLLATE utf8mb4_unicode_ci;

USE `green_crops_db`;

-- Удаление старой таблицы при необходимости
DROP TABLE IF EXISTS `locations`;

-- =========================================================
-- Таблица: locations (Офисы и Поля)
-- =========================================================
CREATE TABLE `locations` (
    `id` INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    `type` ENUM('office', 'field') NOT NULL COMMENT 'Тип объекта: office или field',
    `name` VARCHAR(255) NOT NULL COMMENT 'Название объекта',
    `lat` DECIMAL(10, 7) NOT NULL COMMENT 'Широта (центр объекта)',
    `lng` DECIMAL(10, 7) NOT NULL COMMENT 'Долгота (центр объекта)',
    
    -- Поля для офисов
    `address` VARCHAR(255) NULL COMMENT 'Адрес офиса',
    `phone` VARCHAR(50) NULL COMMENT 'Контактный телефон',
    `email` VARCHAR(100) NULL COMMENT 'Контактный email',
    
    -- Поля для полей (сельхозугодий)
    `area` DECIMAL(10, 2) NULL COMMENT 'Площадь в гектарах',
    `crop` VARCHAR(100) NULL COMMENT 'Выращиваемая культура',
    
    -- Общее описание
    `description` TEXT NULL COMMENT 'Подробное описание объекта',
    
    -- Координаты полигона границ (в формате JSON массива: [{"lat": 52.1, "lng": 20.2}, ...])
    `polygon` JSON NULL COMMENT 'Геометрические границы поля в формате JSON',
    
    -- Служебные поля
    `is_active` TINYINT(1) NOT NULL DEFAULT 1 COMMENT 'Статус активности (1 - активен, 0 - скрыт)',
    `created_at` TIMESTAMP DEFAULT CURRENT_TIMESTAMP COMMENT 'Дата создания',
    `updated_at` TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT 'Дата обновления'
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Индексы для быстрого поиска и фильтрации
CREATE INDEX `idx_locations_type` ON `locations` (`type`);
CREATE INDEX `idx_locations_active` ON `locations` (`is_active`);

